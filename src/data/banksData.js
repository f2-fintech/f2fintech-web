/* ─── Helper: Get bank by slug + loanType ──────────── */
export function getBankBySlug(loanType, bankSlug) {
  for (const bank of ALL_BANKS) {
    const lt = bank.loanTypes[loanType];
    if (lt && lt.slug === bankSlug) {
      return { bank, loanTypeData: lt, loanType };
    }
  }
  return null;
}

/* ─── Helper: Get banks for a loanType ─────────────── */
export function getBanksByLoanType(loanType) {
  return ALL_BANKS.map((bank) => {
    const lt = bank.loanTypes[loanType];
    return lt ? { bank, loanTypeData: lt } : null;
  }).filter(Boolean);
}
