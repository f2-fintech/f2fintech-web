/* ─── Helper: Get bank by slug + loanType ──────────── */
export function getBankBySlug(loanType, bankSlug) {
  for (const bank of ALL_BANKS) {
    const lt = bank.loanTypes[loanType];
    if (lt && lt.slug === bankSlug) {
      return { bank, loanTypeData: lt, loanType };
    }
  }
  return null;
}

/* ─── Helper: Get banks for a loanType ─────────────── */
export function getBanksByLoanType(loanType) {
  return ALL_BANKS.map((bank) => {
    const lt = bank.loanTypes[loanType];
    return lt ? { bank, loanTypeData: lt } : null;
  }).filter(Boolean);
}

/* ─── Helper: Get sorted / curated banks for TopBanksSection ─── */
export function getTopBanksForSection(loanType) {
  const topNames = TOP_5_BANKS_BY_LOAN_TYPE[loanType] || [];
  const allEligible = getBanksByLoanType(loanType);
  
  // Sort so the top 5 curated lenders from the PDF appear first
  const topBanks = [];
  const remainingBanks = [];
  
  for (const name of topNames) {
    const found = allEligible.find((item) => item.bank.name.toLowerCase() === name.toLowerCase());
    if (found) topBanks.push(found);
  }
  
  for (const item of allEligible) {
    if (!topNames.some((name) => name.toLowerCase() === item.bank.name.toLowerCase())) {
      remainingBanks.push(item);
    }
  }
  
  // Sort remaining banks by lowest interest rate
  remainingBanks.sort((a, b) => a.loanTypeData.rateMin - b.loanTypeData.rateMin);
  
  return {
    top5: topBanks,
    all: [...topBanks, ...remainingBanks],
  };
}
