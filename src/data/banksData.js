// Custom helper to quickly generate template loan type data
function makeLoanData({
  bankName,
  slug,
  rateMin,
  rateMax,
  amountText,
  minAmt,
  maxAmt,
  tenure,
  emi,
  emiPerLakh,
  feeText,
  tagline,
  about,
  eligibility,
  ratesList,
  documents,
  faqs,
  feeDetails,
}) {
  return {
    slug,
    interestRate: rateMin.toFixed(2),
    rateRange: `${rateMin.toFixed(2)}% – ${rateMax.toFixed(2)}%`,
    negotiatedRate: rateMin.toFixed(2),
    loanAmount: amountText,
    loanAmountMin: minAmt,
    loanAmountMax: maxAmt,
    maxLoanNum: maxAmt,
    ltv: slug.includes("property") ? "65%" : (slug.includes("home") ? "90%" : "N/A"),
    tenure,
    emi,
    emiPerLakh,
    processingFee: feeText,
    foreclosure: "NIL after 6 months",
    prepayment: "NIL after 6 months",
    tagline,
    highlights: [
      { label: "Interest Rate", value: `${rateMin.toFixed(2)}% p.a.`, icon: "percent" },
      { label: "Max Tenure", value: `${tenure} Years`, icon: "clock" },
      { label: "Max Loan", value: amountText.split("–")[1]?.trim() || amountText, icon: "building" },
      { label: "Processing Fee", value: feeText, icon: "file" },
    ],
    about,
    eligibility: eligibility || [
      "Indian resident aged 21 to 65 years",
      "Stable income source (Salaried or Self-Employed)",
      "Minimum CIBIL score: 700+",
    ],
    interestRates: ratesList || [
      { category: "Preferred Customers", rate: `${rateMin.toFixed(2)}%`, emi: `${emiPerLakh}/Lakh` },
      { category: "Standard Customers", rate: `${rateMax.toFixed(2)}%`, emi: `${emiPerLakh}/Lakh` },
    ],
    documents: documents || [
      "PAN Card & Aadhaar Card",
      "Address Proof",
      "Last 3 months salary slips or ITR verification",
      "Last 6 months bank statements",
    ],
    faq: faqs || [
      { q: "Is collateral required?", a: slug.includes("property") ? "Yes, the property is mortgaged as security." : "No collateral is required." },
      { q: "How long does sanction take?", a: "Usually 3 to 5 business days after document verification." },
    ],
    feeDetails: feeDetails || [
      { label: "Processing Fee", value: feeText },
      { label: "Stamp Duty", value: "At actuals as per state laws" },
    ],
  };
}

