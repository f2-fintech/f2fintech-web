// Custom helper to generate structured loan type data
function makeLoanData({
  bankName,
  slug,
  rateMin,
  rateMax,
  amountText,
  minAmt,
  maxAmt,
  tenure,
  emi,
  emiPerLakh,
  feeText,
  rateRangeText,
  note,
  tagline,
  about,
  eligibility,
  ratesList,
  documents,
  faqs,
  feeDetails,
}) {
  const rangeStr = rateRangeText || `${rateMin.toFixed(2)}% – ${rateMax.toFixed(2)}%`;
  return {
    slug,
    interestRate: rateMin.toFixed(2),
    rateRange: rangeStr,
    negotiatedRate: rateMin.toFixed(2),
    rateMin,
    rateMax,
    note: note || "",
    loanAmount: amountText,
    amountText,
    feeText,
    loanAmountMin: minAmt,
    loanAmountMax: maxAmt,
    maxLoanNum: maxAmt,
    ltv: slug.includes("property") ? "Up to 65%" : (slug.includes("home") ? "Up to 90%" : "N/A"),
    tenure,
    emi,
    emiPerLakh: `₹${emiPerLakh.toLocaleString('en-IN')}`,
    processingFee: feeText,
    foreclosure: "NIL after 6 months",
    prepayment: "NIL after 6 months",
    tagline: tagline || `${bankName} - Best Loan Offers and Rates`,
    highlights: [
      { label: "Interest Rate", value: rangeStr, icon: "percent" },
      { label: "Max Tenure", value: `${tenure} Years`, icon: "clock" },
      { label: "Max Loan", value: amountText.split("–")[1]?.trim() || amountText, icon: "building" },
      { label: "Processing Fee", value: feeText, icon: "file" },
    ],
    about: about || `${bankName} offers competitive rates, transparent terms, and seamless digital approval workflows.`,
    eligibility: eligibility || [
      "Indian resident aged 21 to 65 years",
      "Stable income source (Salaried or Self-Employed)",
      "Minimum CIBIL score: 700+",
    ],
    interestRates: ratesList || [
      { category: "Preferred Customers", rate: `${rateMin.toFixed(2)}%`, emi: `₹${emiPerLakh}/Lakh` },
      { category: "Standard Customers", rate: `${rateMax.toFixed(2)}%`, emi: `₹${emiPerLakh}/Lakh` },
    ],
    documents: documents || [
      "PAN Card & Aadhaar Card",
      "Address Proof",
      "Last 3 months salary slips or ITR verification",
      "Last 6 months bank statements",
    ],
    faq: faqs || [
      { q: "Is collateral required?", a: slug.includes("property") ? "Yes, the property is mortgaged as security." : "No collateral is required for unsecured loans." },
      { q: "How long does sanction take?", a: "Usually 3 to 5 business days after document verification." },
      { q: "Are there any foreclosure charges?", a: "NIL after 6 months as per standard policy." },
    ],
    feeDetails: feeDetails || [
      { label: "Processing Fee", value: feeText },
      { label: "Stamp Duty", value: "At actuals as per state laws" },
      { label: "Foreclosure / Prepayment", value: "NIL after 6 months" },
    ],
  };
}

function slugify(text) {
  return text.toLowerCase().replace('&', 'and').replace(/\s+/g, '-').replace(/\./g, '');
}

